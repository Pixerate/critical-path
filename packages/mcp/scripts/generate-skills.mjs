#!/usr/bin/env node
// Bundles skills/<name>/SKILL.md into src/skills/catalog.generated.ts, so the MCP server and the
// browser (WebMCP) can serve skills without reading files at runtime. Run by `pnpm build`.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageDir = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SKILLS_DIR = join(packageDir, 'skills');
export const CATALOG_FILE = join(packageDir, 'src', 'skills', 'catalog.generated.ts');

/** Parses the `name` and `description` frontmatter of a SKILL.md. */
export function parseSkill(source, file) {
  const match = source.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) throw new Error(`${file}: missing frontmatter`);
  const fields = Object.fromEntries(
    match[1].split('\n').map((line) => {
      const i = line.indexOf(':');
      return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
    })
  );
  if (!fields.name || !fields.description) throw new Error(`${file}: frontmatter needs name and description`);
  return { name: fields.name, description: fields.description, content: source };
}

export function readSkills(dir = SKILLS_DIR) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(dir, entry.name, 'SKILL.md')))
    .map((entry) => {
      const file = join(dir, entry.name, 'SKILL.md');
      const skill = parseSkill(readFileSync(file, 'utf8'), file);
      if (skill.name !== entry.name) throw new Error(`${file}: name "${skill.name}" must match its folder "${entry.name}"`);
      return skill;
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

export function renderCatalog(skills) {
  return `// Generated by scripts/generate-skills.mjs from skills/*/SKILL.md. Do not edit by hand.\nimport type { Skill } from './index.js';\n\nexport const SKILL_CATALOG: Skill[] = ${JSON.stringify(skills, null, 2)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const skills = readSkills();
  writeFileSync(CATALOG_FILE, renderCatalog(skills));
  console.log(`Bundled ${skills.length} skills into ${CATALOG_FILE}`);
}
